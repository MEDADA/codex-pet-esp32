#!/usr/bin/env python3
"""Build the static V41 fallback and the two opaque stage backgrounds."""
import argparse
import json
import math
from pathlib import Path

from PIL import Image
from build_pet_v11_assets import pack_image

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("candidate", type=Path)
parser.add_argument("preview", type=Path)
parser.add_argument("idle_still", type=Path)
args = parser.parse_args()
manifest = json.loads((args.candidate / "source/manifest.json").read_text())
stage = Image.open(args.candidate / manifest["stage"]["file"]).convert("RGBA")
assert stage.size == (466, 466)
blob = bytearray()
decl = [
    "/* Generated by tools/build_pet_v41_assets.py. */",
    "#pragma once",
    '#include "lvgl.h"',
    'extern const uint8_t pet_v41_pixels[] asm("_binary_pet_v41_layers_bin_start");',
]


def emit(name, image, alpha=True):
    while len(blob) % 4:
        blob.append(0)
    offset = len(blob)
    pixels = pack_image(image, alpha)
    color_format = "LV_COLOR_FORMAT_RGB565A8" if alpha else "LV_COLOR_FORMAT_RGB565"
    blob.extend(pixels)
    w, h = image.size
    decl.append(
        f"static const lv_image_dsc_t {name} = {{"
        f".header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf={color_format},"
        f".w={w},.h={h},.stride={w * 2}}},"
        f".data_size={len(pixels)},.data=pet_v41_pixels+{offset}}};"
    )


def light(color, spots):
    layer = Image.new("RGBA", stage.size)
    data = []
    for y in range(466):
        for x in range(466):
            opacity = sum(
                peak * math.exp(-3 * (((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2))
                for cx, cy, rx, ry, peak in spots
            )
            data.append((*color, min(75, round(opacity))))
    layer.putdata(data)
    return layer


character = manifest["character"]
sprite = Image.open(args.candidate / character["file"]).convert("RGBA")
assert tuple(character["size"]) == sprite.size
origin_x, origin_y = character["global_origin_xy"]
target_x, target_y, target_width, target_height = 97, 82, 273, 299


def fit(image, x, y):
    left = target_x + round((x - origin_x) * target_width / sprite.width)
    top = target_y + round((y - origin_y) * target_height / sprite.height)
    right = target_x + round((x + image.width - origin_x) * target_width / sprite.width)
    bottom = target_y + round((y + image.height - origin_y) * target_height / sprite.height)
    return image.resize((right - left, bottom - top), Image.Resampling.LANCZOS), left, top


fitted, _, _ = fit(sprite, origin_x, origin_y)
emit("pet_v41_character", fitted)
decl.append(f"enum {{ pet_v41_x={target_x}, pet_v41_y={target_y} }};")
side_spots = [(76, 224, 135, 176, 68), (390, 224, 135, 176, 68)]
idle_ambient = light((153, 112, 232), side_spots)
work_ambient = light((45, 150, 235), side_spots)
emit("pet_idle_stage", Image.alpha_composite(stage, idle_ambient), False)
emit("pet_work_stage", Image.alpha_composite(stage, work_ambient), False)

out = Path(__file__).resolve().parents[1] / "main/generated"
(out / "pet_v41_layers.bin").write_bytes(blob)
(out / "pet_v41_layers.h").write_text("\n".join(decl) + "\n")
args.preview.mkdir(parents=True, exist_ok=True)
working = stage.copy()
working.alpha_composite(work_ambient)
working.alpha_composite(fitted, (target_x, target_y))
working.save(args.preview / "working-v41.png")
idle = Image.open(args.idle_still).convert("RGBA")
idle.alpha_composite(idle_ambient)
idle_ambient.save(args.preview / "idle-ambient.png")
work_ambient.save(args.preview / "work-ambient.png")
idle.save(args.preview / "idle-v3-light.png")
print(f"Packed {len(blob):,} bytes")
